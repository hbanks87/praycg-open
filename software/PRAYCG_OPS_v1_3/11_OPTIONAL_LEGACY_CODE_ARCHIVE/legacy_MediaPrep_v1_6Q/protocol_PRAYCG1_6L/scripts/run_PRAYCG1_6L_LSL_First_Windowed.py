#!/usr/bin/env python3
"""
PR-AYC-G v1.6L / PRAYCG1.6L PsychoPy + LSL runner with LSL-hardened marker capture.

Major v1.6L changes
--------------------
HARDENS LSL marker capture. The previous 1.6J runner could create a local JSON/CSV event log
while LabRecorder failed to record StasisMarkers into the XDF if recording started before the
marker outlet existed. Version 1.6L brings the marker outlet online before the LabRecorder
hold screen, sends repeated preflight ping markers, uses a unique source_id per run, timestamps
samples with pylsl.local_clock(), and explicitly instructs the operator to click LabRecorder
Update/Start only after the StasisMarkers stream is online. It preserves the 1.6J report/sum
input markers, stillness resets, channel-map markers, cue markers, and objective sum scoring.

Version 1.6L makes the LabRecorder preflight hold windowed instead of fullscreen.
This prevents the operator from being trapped in a fullscreen black PsychoPy menu while trying
to click LabRecorder Update/Start. Fullscreen begins only after LabRecorder is recording.

Run context
-----------
Run this script in PsychoPy Coder/Standalone after pylsl is installed in the PsychoPy
Python environment. Sensor bridges such as OpenBCI, Polar, and Vernier should already
be streaming to LSL and LabRecorder should NOT be started until the script displays the LSL preflight hold screen and StasisMarkers is visible.

Expected media setup
--------------------
- control_video: preferably phase-scrambled from the cue-embedded target video.
- target_video: cue-embedded intact target video.
- override_video: bit-identical copy of target_video.
- cue_schedule_json: generated by praycg_v1_6J_embed_numbers.py.

The control, target, and override files can still be manually selected in the GUI.
"""


ACTIVE_EEG_WATCHDOG = None

class LSLEEGWatchdog:
    """Lightweight live sample-flow monitor for obci_eeg1.

    This does not replace LabRecorder and does not alter the EEG stream. It opens its
    own LSL inlet and pulls samples only to verify that EEG remains alive during the run.
    It emits StasisMarkers warnings if sample flow becomes unstable.
    """
    def __init__(
        self,
        outlet: StreamOutlet,
        logger: EventLogger,
        *,
        stream_name: str = "obci_eeg1",
        expected_rate_hz: float = 125.0,
        resolve_timeout_sec: float = 2.0,
        warning_gap_sec: float = 1.0,
        invalid_gap_sec: float = 3.0,
        rate_window_sec: float = 10.0,
        rate_warn_hz: float = 115.0,
        rate_invalid_hz: float = 100.0,
        heartbeat_sec: float = 10.0,
        max_pull_samples: int = 512,
    ) -> None:
        self.outlet = outlet
        self.logger = logger
        self.stream_name = stream_name
        self.expected_rate_hz = float(expected_rate_hz)
        self.resolve_timeout_sec = float(resolve_timeout_sec)
        self.warning_gap_sec = float(warning_gap_sec)
        self.invalid_gap_sec = float(invalid_gap_sec)
        self.rate_window_sec = float(rate_window_sec)
        self.rate_warn_hz = float(rate_warn_hz)
        self.rate_invalid_hz = float(rate_invalid_hz)
        self.heartbeat_sec = float(heartbeat_sec)
        self.max_pull_samples = int(max_pull_samples)
        self.inlet = None
        self.online = False
        self.samples_total = 0
        self.start_lsl = None
        self.last_sample_ts = None
        self.last_tick_lsl = None
        self.last_heartbeat_lsl = None
        self.recent = []
        self.warning_open = False
        self.dropout_open = False
        self.rate_invalid_open = False
        self.max_gap_seen = 0.0
        self.gaps_gt_250ms = 0

    def connect(self) -> bool:
        streams = resolve_byprop("name", self.stream_name, timeout=self.resolve_timeout_sec)
        if not streams:
            push_marker(self.outlet, self.logger, "EEG_WATCHDOG_NO_STREAM", phase="SETUP", note=self.stream_name)
            return False
        self.inlet = StreamInlet(streams[0], max_chunklen=self.max_pull_samples)
        self.online = True
        self.start_lsl = local_clock()
        self.last_tick_lsl = self.start_lsl
        self.last_heartbeat_lsl = self.start_lsl
        push_marker(self.outlet, self.logger, "EEG_WATCHDOG_ONLINE", phase="SETUP", note=self.stream_name)
        return True

    def tick(self, phase: str = "") -> None:
        if not self.online or self.inlet is None:
            return
        try:
            samples, timestamps = self.inlet.pull_chunk(timeout=0.0, max_samples=self.max_pull_samples)
        except Exception as exc:
            push_marker(self.outlet, self.logger, "EEG_WATCHDOG_PULL_ERROR", phase=phase, note=repr(exc))
            self.online = False
            return
        now = local_clock()
        if timestamps:
            for ts in timestamps:
                if self.last_sample_ts is not None:
                    gap = float(ts - self.last_sample_ts)
                    if gap > self.max_gap_seen:
                        self.max_gap_seen = gap
                    if gap > 0.25:
                        self.gaps_gt_250ms += 1
                        push_marker(self.outlet, self.logger, "EEG_GAP_GT_250MS", phase=phase, note=f"gap_sec={gap:.6f}")
                self.last_sample_ts = float(ts)
            self.samples_total += len(timestamps)
            self.recent.append((now, len(timestamps)))
            cutoff = now - self.rate_window_sec
            self.recent = [(t, n) for (t, n) in self.recent if t >= cutoff]
            if self.dropout_open:
                push_marker(self.outlet, self.logger, "EEG_DROPOUT_RECOVERED", phase=phase, note=f"samples_total={self.samples_total}")
                self.dropout_open = False
                self.warning_open = False
        if self.last_sample_ts is not None:
            silence = now - self.last_sample_ts
            if silence > self.warning_gap_sec and not self.warning_open:
                push_marker(self.outlet, self.logger, "EEG_GAP_WARNING", phase=phase, note=f"seconds_since_last_sample={silence:.3f}")
                self.warning_open = True
            if silence > self.invalid_gap_sec and not self.dropout_open:
                push_marker(self.outlet, self.logger, "EEG_DROPOUT_DETECTED", phase=phase, note=f"seconds_since_last_sample={silence:.3f}")
                self.dropout_open = True
        if self.last_heartbeat_lsl is not None and (now - self.last_heartbeat_lsl) >= self.heartbeat_sec:
            elapsed = max(1e-9, now - (self.start_lsl or now))
            eff_rate = self.samples_total / elapsed
            span = max(1e-9, self.recent[-1][0] - self.recent[0][0]) if len(self.recent) > 1 else 0.0
            recent_rate = (sum(n for _, n in self.recent) / span) if span > 0 else 0.0
            note = (
                f"samples_total={self.samples_total};effective_rate={eff_rate:.3f};"
                f"recent_rate={recent_rate:.3f};max_gap_seen={self.max_gap_seen:.6f};"
                f"gaps_gt_250ms={self.gaps_gt_250ms};dropout_open={self.dropout_open}"
            )
            push_marker(self.outlet, self.logger, "EEG_WATCHDOG_HEARTBEAT", phase=phase, note=note)
            if recent_rate > 0 and recent_rate < self.rate_warn_hz:
                push_marker(self.outlet, self.logger, "EEG_RATE_WARNING", phase=phase, note=note)
            if recent_rate > 0 and recent_rate < self.rate_invalid_hz and not self.rate_invalid_open:
                push_marker(self.outlet, self.logger, "EEG_RATE_INVALID", phase=phase, note=note)
                self.rate_invalid_open = True
            if recent_rate >= self.rate_warn_hz:
                self.rate_invalid_open = False
            self.last_heartbeat_lsl = now

    def final_note(self) -> str:
        now = local_clock()
        elapsed = max(1e-9, now - (self.start_lsl or now)) if self.start_lsl is not None else 0.0
        eff_rate = self.samples_total / elapsed if elapsed else 0.0
        return (
            f"samples_total={self.samples_total};elapsed={elapsed:.3f};effective_rate={eff_rate:.3f};"
            f"max_gap_seen={self.max_gap_seen:.6f};gaps_gt_250ms={self.gaps_gt_250ms};dropout_open={self.dropout_open}"
        )


def tick_eeg_watchdog(outlet: StreamOutlet, logger: EventLogger, phase: str = "") -> None:
    global ACTIVE_EEG_WATCHDOG
    if ACTIVE_EEG_WATCHDOG is not None:
        ACTIVE_EEG_WATCHDOG.tick(phase=phase)



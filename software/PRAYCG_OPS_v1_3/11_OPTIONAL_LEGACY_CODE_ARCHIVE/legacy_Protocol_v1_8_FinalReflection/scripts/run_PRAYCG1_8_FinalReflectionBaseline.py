def _get_movie_duration(mov: Any) -> Optional[float]:
    for attr in ("duration", "_duration"):
        try:
            val = getattr(mov, attr)
            if val is not None and float(val) > 0:
                return float(val)
        except Exception:
            pass
    return None


def play_video(
    win: visual.Window,
    outlet: StreamOutlet,
    logger: EventLogger,
    video_path: str,
    *,
    phase_name: str,
    cue_events: Sequence[CueEvent] = (),
    emit_cue_markers: bool = True,
    movie_draw_size: Optional[Tuple[int, int]] = None,
) -> None:
    path = Path(video_path).expanduser()
    if not path.exists():
        push_marker(outlet, logger, f"ERROR_MISSING_{phase_name}_MEDIA", phase=phase_name, note=str(path))
        raise FileNotFoundError(path)

    push_marker(outlet, logger, f"{phase_name}_LOAD_OK", phase=phase_name, note=str(path))
    mov_kwargs = {"flipVert": False, "flipHoriz": False, "loop": False}
    mov_kwargs["size"] = tuple(movie_draw_size) if movie_draw_size is not None else (1920, 1080)
    mov = visual.MovieStim(win, str(path), **mov_kwargs)
    if movie_draw_size is not None:
        push_marker(outlet, logger, f"{phase_name}_MOVIE_DRAW_SIZE_{movie_draw_size[0]}x{movie_draw_size[1]}", phase=phase_name)
    duration = _get_movie_duration(mov)
    timeout_limit = (duration + 0.35) if duration else 9999.0

    # First flip after loading gives a clean visual reset before the start marker.
    win.flip()
    core.wait(0.05)

    push_marker(outlet, logger, f"{phase_name}_START", phase=phase_name)
    try:
        mov.play()
    except Exception:
        pass

    play_clock = core.Clock()
    cue_start_sent = set()
    cue_end_sent = set()

    while mov.status != FINISHED:
        t = play_clock.getTime()
        if emit_cue_markers:
            for cue in cue_events:
                if cue.cue_index not in cue_start_sent and t >= cue.start_sec:
                    push_marker(
                        outlet,
                        logger,
                        f"{phase_name}_CUE_{cue.cue_index:03d}_VALUE_{cue.value}_START",
                        phase=phase_name,
                        note=f"t={cue.start_sec:.3f}",
                    )
                    cue_start_sent.add(cue.cue_index)
                if cue.cue_index not in cue_end_sent and t >= cue.end_sec:
                    push_marker(
                        outlet,
                        logger,
                        f"{phase_name}_CUE_{cue.cue_index:03d}_VALUE_{cue.value}_END",
                        phase=phase_name,
                        note=f"t={cue.end_sec:.3f}",
                    )
                    cue_end_sent.add(cue.cue_index)
        mov.draw()
        win.flip()
        check_escape(outlet, logger, win, phase=phase_name)
        tick_eeg_watchdog(outlet, logger, phase_name)
        if play_clock.getTime() >= timeout_limit:
            push_marker(outlet, logger, f"{phase_name}_TIMEOUT_BREAK", phase=phase_name)
            break
    try:
        mov.stop()
    except Exception:
        pass
    push_marker(outlet, logger, f"{phase_name}_END", phase=phase_name)
    win.flip()


def collect_numeric_response(
    win: visual.Window,
    outlet: StreamOutlet,
    logger: EventLogger,
    *,
    phase_name: str,
    expected_sum: Optional[int],
    reward_text: str = "",
) -> Tuple[Optional[int], Optional[bool]]:
    push_marker(outlet, logger, "SUM_INPUT_START", phase=phase_name, note=phase_name)
    push_marker(outlet, logger, f"SUM_INPUT_{phase_name}_START", phase=phase_name)
    push_marker(outlet, logger, f"RESPONSE_{phase_name}_SUM_START", phase=phase_name)
    response = ""
    prompt = visual.TextStim(win, text="", color="white", height=38, wrapWidth=1500, alignText="center")
    event.clearEvents()

    while True:
        prompt.text = (
            "Contextual Override Sum\n\n"
            "Type the running sum of all numbers you saw.\n"
            "Press ENTER when done. Backspace edits.\n\n"
            f"Current answer: {response if response else '_'}"
        )
        prompt.draw()
        win.flip()
        tick_eeg_watchdog(outlet, logger, phase_name)
        keys = event.getKeys(keyList=list("0123456789") + ["backspace", "return", "enter", "escape"])
        for k in keys:
            if k == "escape":
                check_escape(outlet, logger, win, phase=phase_name)
            elif k == "backspace":
                response = response[:-1]
            elif k in ("return", "enter"):
                if response.strip():
                    try:
                        numeric = int(response)
                    except ValueError:
                        numeric = None
                    correct = (numeric == expected_sum) if expected_sum is not None and numeric is not None else None
                    push_marker(outlet, logger, f"RESPONSE_{phase_name}_SUM_{numeric if numeric is not None else 'INVALID'}", phase=phase_name)
                    if expected_sum is not None:
                        push_marker(outlet, logger, f"RESPONSE_{phase_name}_EXPECTED_SUM_{expected_sum}", phase=phase_name)
                    if correct is not None:
                        push_marker(outlet, logger, f"RESPONSE_{phase_name}_SUM_CORRECT_{1 if correct else 0}", phase=phase_name)
                    push_marker(outlet, logger, f"RESPONSE_{phase_name}_SUM_END", phase=phase_name)
                    push_marker(outlet, logger, f"SUM_INPUT_{phase_name}_END", phase=phase_name)
                    push_marker(outlet, logger, "SUM_INPUT_END", phase=phase_name, note=phase_name)

                    if correct and reward_text.strip():
                        msg = visual.TextStim(win, text=reward_text, color="white", height=38, wrapWidth=1500, alignText="center")
                        msg.draw()
                        win.flip()
                        push_marker(outlet, logger, f"REWARD_DISPLAYED_{phase_name}", phase=phase_name, note=reward_text.strip())
                        core.wait(2.0)
                    else:
                        msg_text = "Response recorded."
                        if correct is False:
                            msg_text = "Response recorded."
                        msg = visual.TextStim(win, text=msg_text, color="white", height=38, wrapWidth=1500, alignText="center")
                        msg.draw()
                        win.flip()
                        core.wait(1.0)
                    return numeric, correct
            elif k.isdigit():
                # Prevent runaway accidental input.
                if len(response) < 8:
                    response += k
        core.wait(0.02)


def collect_rating(
    win: visual.Window,
    outlet: StreamOutlet,
    logger: EventLogger,
    *,
    phase_name: str,
    item: str,
) -> int:
    text = (
        f"{item}\n\n"
        "Rate 0-9.\n"
        "0 = none / not at all\n"
        "9 = very high / very strong\n\n"
        "Press one number key."
    )
    stim = visual.TextStim(win, text=text, color="white", height=38, wrapWidth=1500, alignText="center")
    stim.draw()
    win.flip()
    event.clearEvents()
    while True:
        tick_eeg_watchdog(outlet, logger, phase_name)
        keys = event.getKeys(keyList=list("0123456789") + ["escape"])
        if "escape" in keys:
            check_escape(outlet, logger, win, phase=phase_name)
        for k in keys:
            if k.isdigit():
                rating = int(k)
                push_marker(outlet, logger, f"RATING_{phase_name}_{item}_{rating}", phase=phase_name)
                core.wait(0.15)
                return rating
        core.wait(0.02)



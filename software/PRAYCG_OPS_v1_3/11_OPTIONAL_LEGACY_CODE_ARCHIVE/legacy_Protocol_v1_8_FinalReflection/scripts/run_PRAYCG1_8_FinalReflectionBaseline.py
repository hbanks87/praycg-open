def emit_media_selection_markers(
    outlet: StreamOutlet,
    logger: EventLogger,
    cfg: Dict[str, Any],
    cue_payload: Dict[str, Any],
) -> Dict[str, str]:
    """Log selected media/cue provenance and emit concise LSL markers."""
    hashes = {
        "control_video_sha256": file_sha256(str(cfg["control_video"])),
        "target_video_sha256": file_sha256(str(cfg["target_video"])),
        "override_video_sha256": file_sha256(str(cfg["override_video"])),
        "cue_schedule_json_sha256": file_sha256(str(cfg["cue_schedule_json"])),
    }
    run_config_path = logger.log_dir / f"{logger.csv_path.stem}_run_config_media_selection.json"
    safe_cfg = {k: (str(v) if isinstance(v, Path) else v) for k, v in cfg.items()}
    payload = {
        "schema": "PRAYCG1_8_run_media_selection_v1",
        "created_unix_time": time.time(),
        "config": safe_cfg,
        "hashes": hashes,
        "cue_schedule_summary": {
            "schema": cue_payload.get("schema"),
            "cue_count": len(cue_payload.get("cue_events", [])) if isinstance(cue_payload.get("cue_events"), list) else None,
            "expected_sum": cue_payload.get("expected_sum"),
            "input_video": cue_payload.get("input_video"),
            "output_cued_video": cue_payload.get("output_cued_video"),
            "output_override_video": cue_payload.get("output_override_video"),
            "cue_design": cue_payload.get("cue_design", {}),
        },
        "target_override_hash_match": hashes["target_video_sha256"] == hashes["override_video_sha256"],
    }
    run_config_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    push_marker(outlet, logger, "MEDIA_SELECTION_GUI_VERSION_1.8", phase="SETUP", note=str(run_config_path))
    push_marker(outlet, logger, "MEDIA_FILE_SELECTION_START", phase="SETUP")
    push_marker(outlet, logger, "MEDIA_SELECTED_CONTROL_VIDEO", phase="SETUP", note=str(cfg["control_video"]))
    push_marker(outlet, logger, "MEDIA_SELECTED_TARGET_VIDEO", phase="SETUP", note=str(cfg["target_video"]))
    push_marker(outlet, logger, "MEDIA_SELECTED_CONTEXTUAL_OVERRIDE_VIDEO", phase="SETUP", note=str(cfg["override_video"]))
    push_marker(outlet, logger, "MEDIA_SELECTED_CUE_SCHEDULE_JSON", phase="SETUP", note=str(cfg["cue_schedule_json"]))
    push_marker(outlet, logger, f"MEDIA_SHA256_CONTROL_{hashes['control_video_sha256'][:12]}", phase="SETUP", note=hashes["control_video_sha256"])
    push_marker(outlet, logger, f"MEDIA_SHA256_TARGET_{hashes['target_video_sha256'][:12]}", phase="SETUP", note=hashes["target_video_sha256"])
    push_marker(outlet, logger, f"MEDIA_SHA256_OVERRIDE_{hashes['override_video_sha256'][:12]}", phase="SETUP", note=hashes["override_video_sha256"])
    push_marker(outlet, logger, f"MEDIA_SHA256_CUEJSON_{hashes['cue_schedule_json_sha256'][:12]}", phase="SETUP", note=hashes["cue_schedule_json_sha256"])
    push_marker(outlet, logger, f"TARGET_OVERRIDE_HASH_MATCH_{'TRUE' if hashes['target_video_sha256'] == hashes['override_video_sha256'] else 'FALSE'}", phase="SETUP")
    push_marker(outlet, logger, "MEDIA_FILE_SELECTION_END", phase="SETUP", note=str(run_config_path))
    return hashes

def run_full_experiment() -> None:
    logging.console.setLevel(logging.WARNING)
    cfg = collect_gui_config()

    log_dir = Path(str(cfg["log_dir"])).expanduser().resolve()
    logger = EventLogger(log_dir, str(cfg["participant_id"]), str(cfg["session_id"]), str(cfg["run_label"]))

    source_id = f"praycg_stasismarkers_{sanitize_for_filename(str(cfg['participant_id']))}_{sanitize_for_filename(str(cfg['session_id']))}_{uuid.uuid4().hex[:10]}"
    info = StreamInfo("StasisMarkers", "Markers", 1, 0, "string", source_id)
    desc = info.desc()
    desc.append_child_value("protocol", "PRAYCG")
    desc.append_child_value("protocol_version", "1.8")
    desc.append_child_value("source_id", source_id)
    desc.append_child_value("marker_capture_rule", "Start LabRecorder only after LSL_PREFLIGHT_HOLD_START appears and StasisMarkers is visible.")
    outlet = StreamOutlet(info, chunk_size=1, max_buffered=3600)
    core.wait(0.75)
    logger.log("LOCAL_LOG_CREATED", phase="SETUP", note=str(logger.csv_path))
    push_marker(outlet, logger, "STASIS_MARKER_STREAM_ONLINE", phase="SETUP", note=source_id)
    push_marker(outlet, logger, "PRAYCG_VERSION_1.8", phase="SETUP")
    push_marker(outlet, logger, "STASIS_MARKER_SOURCE_ID_RECORDED", phase="SETUP", note=source_id)
    push_marker(outlet, logger, "LABRECORDER_START_AFTER_THIS_MARKER_STREAM_IS_ONLINE", phase="SETUP")
    push_marker(outlet, logger, f"STILLNESS_RESET_SECONDS_{float(cfg['stillness_reset_seconds']):.1f}", phase="SETUP")
    push_marker(outlet, logger, f"REPORT_INPUT_EXCLUSION_PREPAD_SEC_{REPORT_INPUT_EXCLUSION_PREPAD_SEC:.1f}", phase="SETUP")
    push_marker(outlet, logger, f"REPORT_INPUT_EXCLUSION_POSTPAD_SEC_{REPORT_INPUT_EXCLUSION_POSTPAD_SEC:.1f}", phase="SETUP")
    push_marker(outlet, logger, f"FINAL_REFLECTION_BASELINE_ENABLED_{'TRUE' if bool(cfg.get('enable_final_reflection_baseline', True)) else 'FALSE'}", phase="SETUP")
    push_marker(outlet, logger, f"FINAL_REFLECTION_BASELINE_SECONDS_{float(cfg.get('final_reflection_baseline_seconds', DEFAULT_FINAL_REFLECTION_BASELINE_SEC)):.1f}", phase="SETUP")
    push_marker(outlet, logger, f"MOVIE_DISPLAY_MODE_{sanitize_marker_part(str(cfg.get('movie_display_mode', 'safe_fit')).lower())}", phase="SETUP")
    push_marker(outlet, logger, f"MOVIE_SAFE_FIT_FRACTION_{float(cfg.get('movie_safe_fit_fraction', DEFAULT_MOVIE_SAFE_FIT_FRACTION)):.3f}", phase="SETUP")

    # v1.8: cue schedule and exact media paths are explicit GUI selections.
    # If the cue JSON cannot be loaded, hard-stop before the run instead of silently
    # continuing with missing cue markers / missing objective sum scoring.
    cue_events, expected_sum_from_schedule, cue_payload = load_cue_schedule(str(cfg["cue_schedule_json"]))
    if not cue_events:
        push_marker(outlet, logger, "ERROR_CUE_SCHEDULE_NOT_LOADED_ABORT", phase="SETUP", note=str(cfg["cue_schedule_json"]))
        logger.close()
        raise RuntimeError(f"Cue schedule did not load or had no cue_events: {cfg['cue_schedule_json']}")
    emit_media_selection_markers(outlet, logger, cfg, cue_payload)

    if bool(cfg.get("use_standard_channel_map", True)):
        emit_channel_map_markers(
            outlet,
            logger,
            PRAYCG16_FIXED_CHANNEL_MAP,
            map_label=str(cfg.get("channel_map_label", "PRAYCG16_FIXED_ORDER_v1")),
            confirmed=bool(cfg.get("channel_map_confirmed", False)),
            confidence=str(cfg.get("channel_map_confidence", "UNKNOWN")),
            notes=str(cfg.get("channel_map_notes", "")),
        )
    else:
        push_marker(outlet, logger, "CHANNEL_MAP_NOT_EMITTED", phase="SETUP", note="use_standard_channel_map=False")
        push_marker(outlet, logger, "CHANNEL_MAP_UNCONFIRMED_DO_NOT_USE_ROI", phase="SETUP", note="No channel map emitted.")

    expected_sum: Optional[int] = expected_sum_from_schedule
    if str(cfg["expected_sum_manual"]).strip():
        expected_sum = parse_int(cfg["expected_sum_manual"], expected_sum_from_schedule or -1)
    if expected_sum is not None and expected_sum >= 0:
        push_marker(outlet, logger, f"CUE_SCHEDULE_EXPECTED_SUM_{expected_sum}", phase="SETUP")
    if cue_events:
        push_marker(outlet, logger, f"CUE_SCHEDULE_LOADED_N_{len(cue_events)}", phase="SETUP", note=str(cfg["cue_schedule_json"]))
    else:
        push_marker(outlet, logger, "CUE_SCHEDULE_NOT_LOADED", phase="SETUP", note=str(cfg["cue_schedule_json"]))

    # Stream inventory snapshot. This is only advisory; LabRecorder is the ground truth.
    stream_names = resolve_stream_names(timeout=0.75)
    logger.log("STREAM_INVENTORY", phase="SETUP", note=",".join(stream_names))

    # v1.8: optional live EEG watchdog. This checks that obci_eeg1 is actively
    # producing samples, not merely visible as an LSL stream header.
    global ACTIVE_EEG_WATCHDOG
    ACTIVE_EEG_WATCHDOG = None
    if bool(cfg.get("enable_eeg_watchdog", True)):
        ACTIVE_EEG_WATCHDOG = LSLEEGWatchdog(
            outlet,
            logger,
            stream_name=str(cfg.get("eeg_watchdog_stream_name", "obci_eeg1")),
            expected_rate_hz=float(cfg.get("eeg_watchdog_expected_rate_hz", 125.0)),
            warning_gap_sec=float(cfg.get("eeg_watchdog_warning_gap_sec", 1.0)),
            invalid_gap_sec=float(cfg.get("eeg_watchdog_invalid_gap_sec", 3.0)),
            rate_warn_hz=float(cfg.get("eeg_watchdog_rate_warn_hz", 115.0)),
            rate_invalid_hz=float(cfg.get("eeg_watchdog_rate_invalid_hz", 100.0)),
        )
        if not ACTIVE_EEG_WATCHDOG.connect():
            push_marker(outlet, logger, "ERROR_EEG_WATCHDOG_STREAM_NOT_FOUND_ABORT", phase="SETUP", note=str(cfg.get("eeg_watchdog_stream_name", "obci_eeg1")))
            logger.close()
            raise RuntimeError("EEG watchdog could not resolve the live EEG stream. Start BrainFlow-to-LSL first.")
        # Pull a few seconds before LabRecorder hold so the operator knows the stream is live.
        precheck_clock = core.Clock()
        push_marker(outlet, logger, "EEG_WATCHDOG_PREFLIGHT_SAMPLE_CHECK_START", phase="SETUP")
        while precheck_clock.getTime() < 3.0:
            tick_eeg_watchdog(outlet, logger, "SETUP")
            core.wait(0.02)
        push_marker(outlet, logger, "EEG_WATCHDOG_PREFLIGHT_SAMPLE_CHECK_END", phase="SETUP", note=ACTIVE_EEG_WATCHDOG.final_note())


    win = None

    # v1.6L/v1.6R correction: keep the LabRecorder preflight as a normal window so the
    # operator can Alt-Tab / click LabRecorder Update / Start without being trapped
    # inside a fullscreen black PsychoPy window. The StasisMarkers outlet is already
    # online at this point and LSL_PREFLIGHT_PING markers are being emitted.
    preflight_win = visual.Window(
        size=(980, 680),
        fullscr=False,
        screen=0,
        units="pix",
        color=[-1, -1, -1],
        allowGUI=True,
    )
    try:
        wait_for_right_click(preflight_win, outlet, logger)
    finally:
        try:
            preflight_win.close()
        except Exception:
            pass
    core.wait(0.35)

    # Only now enter the experiment display mode. This is the first fullscreen window.
    win = visual.Window(
        size=(1920, 1080),
        fullscr=bool(cfg["fullscreen"]),
        screen=int(cfg["screen_index"]),
        units="pix",
        color=[-1, -1, -1],
        allowGUI=False,
    )
    fixation = visual.TextStim(win, text="+", color="white", height=56)
    natural_movie_size = _extract_video_size_from_payload(cue_payload)
    movie_draw_size = calculate_movie_draw_size(win, cfg, natural_movie_size)
    push_marker(outlet, logger, f"MOVIE_NATURAL_SIZE_{natural_movie_size[0]}x{natural_movie_size[1]}", phase="SETUP")
    push_marker(outlet, logger, f"MOVIE_DRAW_SIZE_{movie_draw_size[0]}x{movie_draw_size[1]}", phase="SETUP")

    try:
        push_marker(outlet, logger, "PROTOCOL_SEQUENCE_START", phase="PROTOCOL")

        run_baseline(win, outlet, logger, fixation, duration=float(cfg["baseline_seconds"]), phase_name="BASELINE_1")

        show_instruction_wait_then_stillness(
            win,
            outlet,
            logger,
            "Control block.\n\nWatch the screen naturally. Keep your eyes forward and stay relaxed.",
            phase="CONTROL_1",
            marker_prefix="CONTROL_1_INSTRUCTION",
            stillness_duration=float(cfg["stillness_reset_seconds"]),
            stillness_phase_name="CONTROL_1_PRE_START_STILLNESS",
            stillness_reason="after_control_instruction_proceed_before_control_video",
        )
        play_video(win, outlet, logger, str(cfg["control_video"]), phase_name="CONTROL_1", cue_events=(), emit_cue_markers=False, movie_draw_size=movie_draw_size)
        run_baseline(win, outlet, logger, fixation, duration=float(cfg["washout_seconds"]), phase_name="WASHOUT_1")
        collect_phase_ratings(win, outlet, logger, phase_name="CONTROL_1_AFTER_WASHOUT_1")

        show_instruction_wait_then_stillness(
            win,
            outlet,
            logger,
            (
                "Target block.\n\n"
                "Watch naturally. Let the story land if it lands.\n"
                "Small numbers may appear. Ignore them. Do not count them."
            ),
            phase="TARGET_1",
            marker_prefix="TARGET_1_INSTRUCTION",
            stillness_duration=float(cfg["stillness_reset_seconds"]),
            stillness_phase_name="TARGET_1_PRE_START_STILLNESS",
            stillness_reason="after_target_instruction_proceed_before_target_video",
        )
        play_video(win, outlet, logger, str(cfg["target_video"]), phase_name="TARGET_1", cue_events=cue_events, emit_cue_markers=True, movie_draw_size=movie_draw_size)
        run_baseline(win, outlet, logger, fixation, duration=float(cfg["washout_seconds"]), phase_name="WASHOUT_2")
        collect_phase_ratings(win, outlet, logger, phase_name="TARGET_1_AFTER_WASHOUT_2")

        expected_text = "" if expected_sum is None else "The correct answer is stored privately and will be checked after you respond."
        show_instruction_wait_then_stillness(
            win,
            outlet,
            logger,
            (
                "Contextual Override block.\n\n"
                "Watch the same story, but this time perform the counting task.\n"
                "Every time a number appears, add it to a running sum in your head.\n"
                "You will type the final sum immediately after the video.\n"
                f"{expected_text}"
            ),
            phase="CONTEXTUAL_OVERRIDE_1",
            marker_prefix="CONTEXTUAL_OVERRIDE_1_INSTRUCTION",
            stillness_duration=float(cfg["stillness_reset_seconds"]),
            stillness_phase_name="CONTEXTUAL_OVERRIDE_1_PRE_START_STILLNESS",
            stillness_reason="after_override_instruction_proceed_before_override_video",
        )
        if expected_sum is not None:
            push_marker(outlet, logger, f"CONTEXTUAL_OVERRIDE_1_EXPECTED_SUM_{expected_sum}", phase="CONTEXTUAL_OVERRIDE_1")
        play_video(
            win,
            outlet,
            logger,
            str(cfg["override_video"]),
            phase_name="CONTEXTUAL_OVERRIDE_1",
            cue_events=cue_events,
            emit_cue_markers=True,
            movie_draw_size=movie_draw_size,
        )
        collect_numeric_response(
            win,
            outlet,
            logger,
            phase_name="CONTEXTUAL_OVERRIDE_1",
            expected_sum=expected_sum,
            reward_text=str(cfg["reward_text"]),
        )
        return_to_stillness(
            win, outlet, logger,
            phase_name="CONTEXTUAL_OVERRIDE_1_SUM_ENTRY",
            duration=float(cfg["stillness_reset_seconds"]),
            reason="after_sum_input_before_washout_3",
        )
        run_baseline(win, outlet, logger, fixation, duration=float(cfg["washout_seconds"]), phase_name="WASHOUT_3")
        collect_phase_ratings(win, outlet, logger, phase_name="OVERRIDE_1_AFTER_WASHOUT_3")

        if bool(cfg.get("enable_final_reflection_baseline", True)):
            show_instruction_wait_then_stillness(
                win,
                outlet,
                logger,
                (
                    "Final reflection baseline.\n\n"
                    "Before the final two-minute baseline, reflect quietly on the three video blocks.\n"
                    "Compare how the scrambled/static Control, the natural Target, and the Contextual Override felt emotionally in relation to each other.\n"
                    "Do not type yet. After you press SPACE, sit back, settle, and let the comparison rest in mind while staying still."
                ),
                phase="BASELINE_2_REFLECTION",
                marker_prefix="BASELINE_2_REFLECTION_INSTRUCTION",
                stillness_duration=float(cfg["stillness_reset_seconds"]),
                stillness_phase_name="BASELINE_2_REFLECTION_PRE_START_STILLNESS",
                stillness_reason="after_washout3_reports_before_final_reflection_baseline",
            )
            run_baseline(
                win,
                outlet,
                logger,
                fixation,
                duration=float(cfg.get("final_reflection_baseline_seconds", DEFAULT_FINAL_REFLECTION_BASELINE_SEC)),
                phase_name="BASELINE_2_REFLECTION",
            )
            collect_final_master_report(win, outlet, logger)
        else:
            push_marker(outlet, logger, "FINAL_REFLECTION_BASELINE_SKIPPED", phase="PROTOCOL")

        push_marker(outlet, logger, "PROTOCOL_SEQUENCE_END", phase="PROTOCOL")
        if ACTIVE_EEG_WATCHDOG is not None:
            push_marker(outlet, logger, "EEG_WATCHDOG_FINAL_SUMMARY", phase="PROTOCOL", note=ACTIVE_EEG_WATCHDOG.final_note())
    finally:
        logger.close()
        try:
            if win is not None:
                win.close()
        except Exception:
            pass
        core.quit()


if __name__ == "__main__":
    run_full_experiment()

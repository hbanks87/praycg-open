class EventLogger:
    def __init__(self, log_dir: Path, participant_id: str, session_id: str, run_label: str) -> None:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        safe_pid = sanitize_for_filename(participant_id or "P001")
        safe_sid = sanitize_for_filename(session_id or "S001")
        safe_run = sanitize_for_filename(run_label or "run")
        self.log_dir = log_dir
        self.log_dir.mkdir(parents=True, exist_ok=True)
        self.csv_path = self.log_dir / f"PRAYCG_v1_8_{safe_pid}_{safe_sid}_{safe_run}_{timestamp}_events.csv"
        self.json_path = self.log_dir / f"PRAYCG_v1_8_{safe_pid}_{safe_sid}_{safe_run}_{timestamp}_events.json"
        self.rows: List[Dict[str, Any]] = []
        self.csv_file = self.csv_path.open("w", newline="", encoding="utf-8")
        self.writer = csv.DictWriter(
            self.csv_file,
            fieldnames=["marker", "phase", "note", "lsl_time", "unix_time", "psychopy_time"],
        )
        self.writer.writeheader()

    def log(self, marker: str, phase: str = "", note: str = "", lsl_time_override: Optional[float] = None) -> None:
        row = {
            "marker": marker,
            "phase": phase,
            "note": note,
            "lsl_time": float(lsl_time_override) if lsl_time_override is not None else local_clock(),
            "unix_time": time.time(),
            "psychopy_time": core.getTime(),
        }
        self.rows.append(row)
        self.writer.writerow(row)
        self.csv_file.flush()

    def close(self) -> None:
        self.csv_file.flush()
        self.csv_file.close()
        self.json_path.write_text(json.dumps(self.rows, indent=2), encoding="utf-8")


def sanitize_for_filename(text: str) -> str:
    text = (text or "").strip()
    text = re.sub(r"[^A-Za-z0-9_.-]+", "_", text)
    return text.strip("_") or "NA"


def sanitize_marker_part(text: str) -> str:
    text = (text or "").strip()
    text = re.sub(r"[^A-Za-z0-9_.-]+", "_", text)
    return text.strip("_") or "NA"


def push_marker(outlet: StreamOutlet, logger: EventLogger, marker: str, phase: str = "", note: str = "") -> None:
    """Push one marker to LSL and mirror it to the local CSV/JSON log.

    The local log is useful, but the XDF stream is the authority for physiology alignment.
    Version 1.8 therefore timestamps the LSL sample explicitly with pylsl.local_clock()
    and requests pushthrough when the installed pylsl version supports it.
    """
    marker = sanitize_marker_part(marker)
    ts = local_clock()
    try:
        outlet.push_sample([marker], timestamp=ts, pushthrough=True)
    except TypeError:
        # Older pylsl builds may not expose pushthrough as a keyword.
        outlet.push_sample([marker], timestamp=ts)
    logger.log(marker, phase=phase, note=note, lsl_time_override=ts)
    print(f"MARKER {marker} | lsl_time={ts:.6f} | phase={phase} | note={note}")




def write_channel_map_csv(
    logger: EventLogger,
    rows: Sequence[Tuple[int, str, str]],
    *,
    map_label: str,
    confirmed: bool,
    confidence: str,
    notes: str = "",
) -> Path:
    out = logger.log_dir / f"{logger.csv_path.stem}_channel_map.csv"
    with out.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=["openbci_channel", "electrode_location", "roi", "map_label", "confirmed", "confidence", "notes"],
        )
        writer.writeheader()
        for ch, electrode, roi in rows:
            writer.writerow({
                "openbci_channel": ch,
                "electrode_location": electrode,
                "roi": roi,
                "map_label": map_label,
                "confirmed": int(bool(confirmed)),
                "confidence": confidence,
                "notes": notes,
            })
    return out


def emit_channel_map_markers(
    outlet: StreamOutlet,
    logger: EventLogger,
    rows: Sequence[Tuple[int, str, str]],
    *,
    map_label: str,
    confirmed: bool,
    confidence: str,
    notes: str = "",
) -> None:
    """Emit parseable LSL markers documenting OpenBCI channel -> electrode mapping."""
    clean_label = sanitize_marker_part(map_label)
    clean_conf = sanitize_marker_part(confidence.upper())
    csv_path = write_channel_map_csv(logger, rows, map_label=map_label, confirmed=confirmed, confidence=confidence, notes=notes)

    push_marker(outlet, logger, "CHANNEL_MAP_START", phase="SETUP", note=str(csv_path))
    push_marker(outlet, logger, f"CHANNEL_MAP_LABEL_{clean_label}", phase="SETUP", note=map_label)
    push_marker(outlet, logger, f"CHANNEL_MAP_CONFIRMED_{'TRUE' if confirmed else 'FALSE'}", phase="SETUP", note=notes)
    push_marker(outlet, logger, f"CHANNEL_MAP_CONFIDENCE_{clean_conf}", phase="SETUP", note=confidence)
    if not confirmed or clean_conf in {"UNKNOWN", "UNCONFIRMED", "NONE"}:
        push_marker(outlet, logger, "CHANNEL_MAP_UNCONFIRMED_DO_NOT_USE_ROI", phase="SETUP", note=notes)
    for ch, electrode, roi in rows:
        push_marker(
            outlet,
            logger,
            f"CHANNEL_MAP_CH{int(ch):02d}_{sanitize_marker_part(electrode)}_ROI_{sanitize_marker_part(roi)}",
            phase="SETUP",
            note=f"channel={ch};electrode={electrode};roi={roi};map_label={map_label};confirmed={confirmed};confidence={confidence}",
        )
    push_marker(outlet, logger, "CHANNEL_MAP_END", phase="SETUP", note=str(csv_path))


def check_escape(outlet: StreamOutlet, logger: EventLogger, win: visual.Window, phase: str = "") -> None:
    if "escape" in event.getKeys(keyList=["escape"]):
        push_marker(outlet, logger, "EMERGENCY_KILL", phase=phase)
        logger.close()
        win.close()
        core.quit()


def parse_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    s = str(value).strip().lower()
    return s in {"1", "true", "yes", "y", "on"}


def parse_int(value: Any, default: int) -> int:
    try:
        return int(str(value).strip())
    except Exception:
        return default


def parse_float(value: Any, default: float) -> float:
    try:
        return float(str(value).strip())
    except Exception:
        return default


def clamp_float(value: float, low: float, high: float) -> float:
    return max(low, min(high, float(value)))


def resolve_stream_names(timeout: float = 1.0) -> List[str]:
    streams = resolve_byprop("type", "", timeout=timeout)
    names = []
    for stream in streams:
        try:
            names.append(stream.name())
        except Exception:
            pass
    # resolve_byprop('', '') can be backend-sensitive. Try broad common types if empty.
    if not names:
        for stream_type in ["EEG", "Markers", "HRV", "ECG", "Respiration", "RespirationBelt"]:
            for stream in resolve_byprop("type", stream_type, timeout=0.25):
                try:
                    names.append(stream.name())
                except Exception:
                    pass
    return sorted(set(names))


def load_cue_schedule(path: str) -> Tuple[List[CueEvent], Optional[int], Dict[str, Any]]:
    if not path or not Path(path).exists():
        return [], None, {}
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    cues = []
    for row in payload.get("cue_events", []):
        cues.append(
            CueEvent(
                cue_index=int(row["cue_index"]),
                value=int(row["value"]),
                start_sec=float(row["start_sec"]),
                end_sec=float(row["end_sec"]),
            )
        )
    expected = payload.get("expected_sum", None)
    expected_int = int(expected) if expected is not None and str(expected).strip() else None
    return cues, expected_int, payload


def show_text_and_wait(
    win: visual.Window,
    outlet: StreamOutlet,
    logger: EventLogger,
    text: str,
    *,
    phase: str,
    marker_prefix: str,
    key_list: Sequence[str] = ("space", "return"),
) -> None:
    push_marker(outlet, logger, f"{marker_prefix}_START", phase=phase)
    stim = visual.TextStim(win, text=text, color="white", height=32, wrapWidth=1550, alignText="center")
    stim.draw()
    win.flip()
    event.clearEvents()
    while True:
        keys = event.getKeys(keyList=list(key_list) + ["escape"])
        if "escape" in keys:
            check_escape(outlet, logger, win, phase=phase)
        if any(k in keys for k in key_list):
            break
        tick_eeg_watchdog(outlet, logger, phase)
        core.wait(0.02)
    win.flip()
    push_marker(outlet, logger, f"{marker_prefix}_END", phase=phase)


def show_instruction_wait_then_stillness(
    win: visual.Window,
    outlet: StreamOutlet,
    logger: EventLogger,
    text: str,
    *,
    phase: str,
    marker_prefix: str,
    stillness_duration: float,
    stillness_phase_name: Optional[str] = None,
    stillness_reason: str = "",
) -> None:
    """Show a proceed screen, then run stillness before the next analyzable block.

    v1.6R transition rule:
        report/input -> press SPACE to proceed -> stillness countdown -> clip/block starts.

    This prevents the final keypress from occurring immediately before the next video,
    which would contaminate the first seconds of the next physiology block with movement,
    posture correction, and hand/shoulder/jaw tension.
    """
    instructional_text = (
        text.rstrip()
        + "\n\nAfter you press SPACE, do not type or move."
        + "\nAn 8-10 second stillness countdown will run, then the next block starts automatically."
    )
    clean_phase = sanitize_marker_part(phase)
    push_marker(outlet, logger, "PROCEED_PROMPT_START", phase=phase, note=marker_prefix)
    push_marker(outlet, logger, f"PROCEED_PROMPT_{clean_phase}_START", phase=phase, note=marker_prefix)
    show_text_and_wait(
        win,
        outlet,
        logger,
        instructional_text,
        phase=phase,
        marker_prefix=marker_prefix,
    )
    push_marker(outlet, logger, f"PROCEED_PROMPT_{clean_phase}_END", phase=phase, note=marker_prefix)
    push_marker(outlet, logger, "PROCEED_PROMPT_END", phase=phase, note=marker_prefix)
    push_marker(outlet, logger, f"{clean_phase}_PROCEED_CONFIRMED_BEFORE_STILLNESS", phase=phase)
    return_to_stillness(
        win,
        outlet,
        logger,
        phase_name=stillness_phase_name or f"{sanitize_marker_part(phase)}_PRE_START_STILLNESS",
        duration=stillness_duration,
        reason=stillness_reason or f"after_{sanitize_marker_part(phase).lower()}_instruction_proceed_before_block_start",
    )


def wait_for_right_click(win: visual.Window, outlet: StreamOutlet, logger: EventLogger) -> None:
    """Hold experiment while StasisMarkers is alive so LabRecorder can capture it.

    This fixes the main 1.6J/1.6L failure mode: starting LabRecorder before the marker
    outlet existed. Do not start LabRecorder before this screen. While this screen is
    visible, the script emits repeated LSL_PREFLIGHT_PING_* markers once per second.
    """
    text = (
        "LSL Marker Stream Is Now Online.\n\n"
        "DO THIS NOW, IN THIS ORDER:\n"
        "1. Open LabRecorder if it is not already open.\n"
        "2. Click UPDATE.\n"
        "3. Confirm these streams are visible and checked:\n"
        "   - StasisMarkers\n"
        "   - obci_eeg1\n"
        "   - PolarHRV if used\n"
        "   - VernierRespirationBelt if used\n"
        "4. Click START in LabRecorder.\n\n"
        "This screen will keep sending LSL_PREFLIGHT_PING markers.\n"
        "This window is intentionally NOT fullscreen so you can Alt-Tab or click LabRecorder.\n"
        "If StasisMarkers is not visible in LabRecorder, stop now and fix it.\n\n"
        "LEFT-CLICK once to focus this screen.\n"
        "RIGHT-CLICK only after LabRecorder is recording StasisMarkers."
    )
    push_marker(outlet, logger, "LSL_PREFLIGHT_HOLD_START", phase="SETUP", note="Start LabRecorder during this hold, not before script launch.")
    msg = visual.TextStim(win, text=text, color="white", height=32, wrapWidth=1600, alignText="center")
    msg.draw()
    win.flip()
    mouse = event.Mouse(win=win)
    mouse.clickReset()
    hold_clock = core.Clock()
    next_ping = 0.0
    ping_n = 0
    while True:
        now = hold_clock.getTime()
        if now >= next_ping:
            ping_n += 1
            push_marker(outlet, logger, f"LSL_PREFLIGHT_PING_{ping_n:03d}", phase="SETUP", note="If LabRecorder records StasisMarkers, this ping should appear in the XDF.")
            next_ping = now + 1.0
        buttons = mouse.getPressed()
        if buttons[2]:
            break
        check_escape(outlet, logger, win, phase="SETUP")
        tick_eeg_watchdog(outlet, logger, "SETUP")
        msg.draw()
        win.flip()
        core.wait(0.03)

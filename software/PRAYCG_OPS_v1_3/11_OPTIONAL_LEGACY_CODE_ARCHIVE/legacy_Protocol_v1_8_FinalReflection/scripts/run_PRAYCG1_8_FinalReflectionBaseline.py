def return_to_stillness(
    win: visual.Window,
    outlet: StreamOutlet,
    logger: EventLogger,
    *,
    phase_name: str,
    duration: float,
    reason: str = "",
) -> None:
    """Insert a non-analysis stillness reset after typing/report movement.

    This block is deliberately bracketed with broad and phase-specific markers. Analysis
    scripts can hard-exclude the report/sum windows and use this reset as a settling buffer
    before the next analyzable physiology block.
    """
    duration = clamp_float(duration, MIN_STILLNESS_RESET_SEC, MAX_STILLNESS_RESET_SEC)
    note = f"duration_sec={duration:.3f};reason={reason}"
    push_marker(outlet, logger, "RETURN_TO_STILLNESS_START", phase=phase_name, note=note)
    push_marker(outlet, logger, f"RETURN_TO_STILLNESS_{phase_name}_START", phase=phase_name, note=note)

    reset_clock = core.Clock()
    stim = visual.TextStim(win, text="", color="white", height=34, wrapWidth=1500, alignText="center")
    while reset_clock.getTime() < duration:
        remaining = max(0.0, duration - reset_clock.getTime())
        stim.text = (
            "Return to stillness.\n\n"
            "Sit back in the chair. Put hands in lap.\n"
            "Relax jaw, shoulders, neck, forehead, and tongue.\n"
            "Eyes on the cross. Breathe normally.\n\n"
            f"Stillness reset: {remaining:0.1f} seconds"
        )
        stim.draw()
        win.flip()
        check_escape(outlet, logger, win, phase=phase_name)
        tick_eeg_watchdog(outlet, logger, phase_name)
        core.wait(0.02)
    win.flip()
    push_marker(outlet, logger, f"RETURN_TO_STILLNESS_{phase_name}_END", phase=phase_name, note=note)
    push_marker(outlet, logger, "RETURN_TO_STILLNESS_END", phase=phase_name, note=note)



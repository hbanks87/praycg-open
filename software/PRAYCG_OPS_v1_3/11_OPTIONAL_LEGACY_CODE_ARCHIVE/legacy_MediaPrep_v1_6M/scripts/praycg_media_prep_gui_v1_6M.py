"""
PRAYCG MediaPrep GUI v1.6M

One-master-MP4 media preparation pipeline for PR-AYC-G.

Given one master .mp4, this tool creates:
  1. cue-embedded Target MP4
  2. bit-identical cue-embedded Contextual Override MP4
  3. phase-scrambled Control MP4 generated from the cue-embedded Target
  4. cue schedule JSON/CSV with expected running-sum answer
  5. media-prep manifest and short Markdown report

Design intent:
  - Target and Contextual Override should use the same cue-embedded video.
  - Only instructions differ: Target = ignore numbers / watch naturally;
    Override = add numbers / report sum.
  - The Control is generated by phase-scrambling the cue-embedded target so that
    the control inherits the same cue-timing/low-level media events while removing
    recognizable narrative structure.

This is a preparation tool, not an experimental runner.
"""

